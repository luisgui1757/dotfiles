func TestSentinelRemovedEarlierTargetsAllowFreshAdoption(t *testing.T) {
	for _, edited := range []bool{false, true} {
		t.Run(map[bool]string{false: "adopted", true: "preserved-edits"}[edited], func(t *testing.T) {
			c, d := sentinelController(t)
			d.Targets[sentinelResource] = []ProfileTarget{
				{filepath.Join(c.Home, ".codex", "AGENTS.md"), sentinelPolicy},
				{filepath.Join(c.Home, ".claude", "CLAUDE.md"), sentinelPolicy},
				{filepath.Join(c.Home, ".config", "opencode", "AGENTS.md"), sentinelPolicy},
			}
			oldTargets := slices.Clone(d.Targets[sentinelResource])
			original := "Personal prose.\n<!-- AGENT-RULES:BEGIN -->\nEarlier policy.\n" + sentinelEnd + "\n"
			originalSnapshots := map[string]configSnapshot{}
			for _, target := range oldTargets {
				writeConfigFixture(t, target.Path, original)
				if err := os.Chmod(target.Path, 0640); err != nil {
					t.Fatal(err)
				}
				_, snapshot, err := readProfile(target.Path)
				if err != nil {
					t.Fatal(err)
				}
				originalSnapshots[target.Path] = snapshot
			}
			dispatchApproved(t, c, Request{Schema: 1, Mode: "apply", Selected: []string{"sentinel"}, Adopt: []string{sentinelResource}})
			if edited {
				data, err := os.ReadFile(oldTargets[0].Path)
				if err != nil {
					t.Fatal(err)
				}
				data = bytes.Replace(data, []byte("# Operating Contract"), []byte("# Personal edited contract"), 1)
				if err := os.WriteFile(oldTargets[0].Path, data, 0640); err != nil {
					t.Fatal(err)
				}
				dispatchApproved(t, c, Request{Schema: 1, Mode: "repair", Adopt: []string{sentinelResource}})
			}
			dispatchApproved(t, c, Request{Schema: 1, Mode: "apply", Selected: []string{}})
			state, err := LoadState(c.StatePath, c.Home)
			if err != nil {
				t.Fatal(err)
			}
			receipt := state.Receipts[sentinelResource]
			if receipt.Status != "removed" || receipt.Ownership != "reused" || edited && len(receipt.After.Preserved) == 0 {
				t.Fatal("fixture did not retain a released receipt", receipt)
			}
			journalPath := d.journalPath(receipt.OperationID)
			journal, err := os.ReadFile(journalPath)
			if err != nil {
				t.Fatal(err)
			}
			preserved := map[string]configSnapshot{}
			for _, path := range receipt.After.Preserved {
				snapshot, err := snapshotTree(path, maxConfigBytes, maxConfigEntries)
				if err != nil {
					t.Fatal(err)
				}
				preserved[path] = snapshot
			}
			if err := configureSentinel(d, ConfigFolders{Home: c.Home}, allSentinelAgents, nil); err != nil {
				t.Fatal(err)
			}
			request := Request{Schema: 1, Mode: "apply", Selected: []string{"sentinel"}}
			plan, err := c.Preview(context.Background(), request)
			if err != nil {
				t.Fatal(err)
			}
			op := operation(t, plan, sentinelResource)
			if op.Action != "pending" || !op.Observed.Adoptable || op.Observed.Pending != "" {
				t.Fatal("released old targets blocked fresh adoption", op.Action, op.Observed.Adoptable, op.Observed.Pending)
			}
			for path := range preserved {
				if !slices.Contains(op.Observed.Preserved, path) {
					t.Fatal("preview lost preserved edit disclosure", path, op)
				}
			}
			request.Adopt = []string{sentinelResource}
			dispatchApproved(t, c, request)
			dispatchApproved(t, c, Request{Schema: 1, Mode: "apply", Selected: []string{}})
			for _, target := range oldTargets {
				data, snapshot, err := readProfile(target.Path)
				if err != nil || string(data) != original || snapshot != originalSnapshots[target.Path] {
					t.Fatal("retargeting lost personal policy or permissions", target.Path, snapshot, err)
				}
			}
			for _, target := range d.Targets[sentinelResource][2:] {
				if _, err := os.Lstat(target.Path); !errors.Is(err, os.ErrNotExist) {
					t.Fatal("newly owned policy survived removal", target.Path, err)
				}
			}
			if after, err := os.ReadFile(journalPath); err != nil || !bytes.Equal(after, journal) {
				t.Fatal("retargeting rewrote old removal evidence", err)
			}
			for path, before := range preserved {
				after, err := snapshotTree(path, maxConfigBytes, maxConfigEntries)
				if err != nil || after != before {
					t.Fatal("retargeting changed retained edits", path, err)
				}
			}
		})
	}
}

func TestSentinelBlocksPreserveEncodingAndPersonalBytes(t *testing.T) {
	fixtures := [][]byte{nil, []byte("personal prose"), []byte("personal café\n"), []byte("personal\r\n"), {0xef, 0xbb, 0xbf}}
	for _, bom := range [][]byte{{0xff, 0xfe}, {0xfe, 0xff}} {
		encode, _, err := profileEncoding(bom)
		if err != nil {
			t.Fatal(err)
		}
		fixtures = append(fixtures, append(bytes.Clone(bom), encode("personal café 🌍\r\n")...))
	}
	for _, before := range fixtures {
		block, err := renderProfileBlock(before, sentinelResource, sentinelPolicy)
		if err != nil {
			t.Fatal(err)
		}
		installed, old, err := replaceProfileBlock(before, sentinelResource, block)
		if err != nil || len(old) != 0 {
			t.Fatal(err, string(old))
		}
		desired, err := renderProfileBlock(installed, sentinelResource, sentinelPolicy)
		if err != nil || !bytes.Equal(desired, block) {
			t.Fatal("installation changes its own desired identity", err)
		}
		again, _, err := replaceProfileBlock(installed, sentinelResource, desired)
		if err != nil || !bytes.Equal(again, installed) {
			t.Fatal("repeat changes policy", err)
		}
		restored, _, err := replaceProfileBlock(installed, sentinelResource, nil)
		if err != nil || !bytes.Equal(restored, before) {
			t.Fatalf("removal changed personal bytes: %x != %x: %v", restored, before, err)
		}
	}
}

