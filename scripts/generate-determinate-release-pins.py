#!/usr/bin/env python3
"""Reproduce authentication pins for the reviewed historical Mac Nix installers."""

import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import urllib.request


REPOSITORY = "DeterminateSystems/nix-installer"
ASSET = "nix-installer-aarch64-darwin"
NEWEST = (3, 23, 3)
TARGET = Path(__file__).resolve().parents[1] / "installer/legacy_determinate_releases.go"


def release_records():
    records = []
    for page in range(1, 11):
        url = f"https://api.github.com/repos/{REPOSITORY}/releases?per_page=100&page={page}"
        with urllib.request.urlopen(url, timeout=60) as response:
            data = response.read((16 << 20) + 1)
        if len(data) > 16 << 20:
            raise ValueError("release metadata exceeds its inspection bound")
        batch = json.loads(data)
        if not isinstance(batch, list):
            raise ValueError("GitHub did not return a release list")
        records.extend(batch)
        if len(batch) < 100:
            return records
    raise ValueError("release inventory exceeds its review bound")


def release_pin(release):
    match = re.fullmatch(r"v(3)\.(\d+)\.(\d+)", release["tag_name"])
    if not match or tuple(map(int, match.groups())) > NEWEST or release["draft"]:
        return None
    assets = [item for item in release["assets"] if item["name"] == ASSET]
    if not assets:
        return None  # For example, v3.19.0 published no Apple Silicon asset.
    if len(assets) != 1:
        raise ValueError("duplicate release asset")
    asset = assets[0]
    size = asset["size"]
    if type(size) is not int or not 0 < size <= 512 << 20:
        raise ValueError("release asset exceeds its inspection bound")
    digest = asset.get("digest")
    if digest is None:
        # Older releases predate GitHub's digest metadata. Hash the exact
        # official asset; never execute it or substitute a newer release.
        url = f"https://github.com/{REPOSITORY}/releases/download/{release['tag_name']}/{ASSET}"
        checksum, count = hashlib.sha256(), 0
        with urllib.request.urlopen(url, timeout=90) as response:
            while chunk := response.read(1 << 20):
                count += len(chunk)
                if count > size:
                    raise ValueError("download exceeds the published asset size")
                checksum.update(chunk)
        if count != size:
            raise ValueError("download differs from the published asset size")
        digest = "sha256:" + checksum.hexdigest()
    if not re.fullmatch(r"sha256:[0-9a-f]{64}", digest):
        raise ValueError("invalid release digest")
    return release["tag_name"][1:], size, digest.removeprefix("sha256:")


def reviewed_tag(release):
    match = re.fullmatch(r"v(3)\.(\d+)\.(\d+)", release["tag_name"])
    return bool(match) and tuple(map(int, match.groups())) <= NEWEST and not release["draft"]


def bundled_nix(release):
    # SetupDefaultProfile installs the Nix built from the release's nix-src
    # flake input. Its version can lag the installer's own version.
    tag = release["tag_name"]
    url = f"https://raw.githubusercontent.com/{REPOSITORY}/{tag}/flake.lock"
    with urllib.request.urlopen(url, timeout=60) as response:
        data = response.read((1 << 20) + 1)
    if len(data) > 1 << 20:
        raise ValueError("flake.lock exceeds its inspection bound")
    lock = json.loads(data)
    node = lock["nodes"][lock["root"]]["inputs"]["nix"]
    if not isinstance(node, str):
        raise ValueError(f"{tag} has an unexpected nix input")
    match = re.search(r"/DeterminateSystems/nix-src/(3\.\d+\.\d+)/", lock["nodes"][node]["locked"].get("url", ""))
    if not match:
        raise ValueError(f"{tag} bundles an unrecognized Nix source")
    return tag[1:], match.group(1)


def version_key(version):
    return tuple(map(int, version.split(".")))


def render(pins, bundled):
    versions = [pin[0] for pin in pins]
    if len(versions) != len(set(versions)) or not pins or not bundled:
        raise ValueError("empty or duplicate release pins")
    rows = []
    for version, size, digest in sorted(pins, key=lambda pin: version_key(pin[0])):
        rows.append(f'\t"{version}": {{"{ASSET}", {size}, "{digest}"}},')
    nix_rows = [f'\t"{version}": "{nix}",' for version, nix in sorted(bundled.items(), key=lambda item: version_key(item[0]))]
    return "\n".join([
        "// Code generated by scripts/generate-determinate-release-pins.py; DO NOT EDIT.",
        "// Source: https://github.com/DeterminateSystems/nix-installer/releases",
        "// Pins authenticate existing bytes; migration never downloads a replacement.",
        "package installer", "", "var legacyDeterminateMacReleases = map[string]legacyDeterminateRelease{",
        *rows, "}", "",
        "// Each reviewed installer release's bundled Determinate Nix version, from",
        "// the nix-src input in its flake.lock. Root's default profile holds it.",
        "var legacyDeterminateBundledNix = map[string]string{",
        *nix_rows, "}", "",
    ])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    releases = release_records()
    pins = [pin for release in releases if (pin := release_pin(release)) is not None]
    bundled = dict(bundled_nix(release) for release in releases if reviewed_tag(release))
    # gofmt is the canonical renderer for the generated Go source.
    rendered = subprocess.run(["gofmt"], input=render(pins, bundled), text=True, capture_output=True, check=True).stdout
    if args.check:
        if TARGET.read_text() != rendered:
            raise SystemExit("Determinate release pins drifted; review regenerated bytes")
    else:
        TARGET.write_text(rendered)
    print(f"Verified {len(pins)} historical Apple Silicon release pins and {len(bundled)} bundled Nix versions")


if __name__ == "__main__":
    main()
